  function simulatePost(shell, post, dayIdx) {
    const r = E().rng(E().hashStr(post.id + ":" + dayIdx));
    const reach = 40 + shell.followers * (0.25 + r() * 0.5);
    const viral = r() < 0.04 ? 6 + r() * 10 : 1;                 /* 4% chance of a breakout */
    const views = Math.round(reach * nicheMeta(shell.niche).heat * personaFit(shell) * shell.quality * viral * (0.6 + r() * 0.9));
    const likes = Math.round(views * (0.03 + r() * 0.05));
    const follows = Math.round(views * (0.004 + r() * 0.009));
    const clicks = Math.round(views * (0.006 + r() * 0.012));
    post.metrics = { views, likes, follows, clicks, viral: viral > 1 };
    return post.metrics;
  }

  function attributeIncome(shell, post, clicks, r) {
    const st = S().state;
    if (post.ctaStyle === "ghost-product" && post.ctaProductId) {
      const p = st.products.find(x => x.id === post.ctaProductId);
      const unit = p && p.price > 0 ? p.price : 14;
      const sales = Math.round(clicks * (0.02 + r() * 0.04));
      return { income: sales * unit, note: sales ? `${sales} assisted sale(s) of "${p ? p.name : "product"}"` : null };
    }
    if (post.ctaStyle === "affiliate") {
      const income = Math.round(clicks * (0.5 + r() * 1.1));
      return { income, note: null };
    }
    if (post.ctaStyle === "email") {
      const emails = Math.round(clicks * (0.25 + r() * 0.3));
      shell.emailList = (shell.emailList || 0) + emails;
      return { income: 0, note: emails ? `+${emails} emails collected` : null };
    }
    if (post.ctaStyle === "lead-gen" && post.ctaCloneId) {
      const clone = st.clones.find(c => c.id === post.ctaCloneId);
      const leads = Math.round(clicks * (0.15 + r() * 0.2));
      if (clone && leads) {
        clone.stats.leads += leads;
        clone.memory.push(`+${leads} leads routed in by Outer Shell ${shell.name}.`);
        return { income: 0, note: `+${leads} leads routed to clone ${clone.name}` };
      }
      return { income: 0, note: null };
    }
    return { income: 0, note: null };
  }

