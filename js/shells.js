  /* Run one sim day for one shell. Returns digest events. */
  function runDay(shell, dayKey, dayIdx, queueAllowed) {
    const r = E().rng(E().hashStr(shell.id + ":" + dayKey));
    const events = [];
    const perDay = Math.min(5, shell.postsPerDay);
    const day = { day: dayKey, followers: shell.followers, views: 0, likes: 0, clicks: 0, income: 0 };

    for (let i = 0; i < perDay; i++) {
      const platform = shell.platforms[i % shell.platforms.length];
      const post = makePost(shell, platform, dayKey, r);
      const m = simulatePost(shell, post, dayIdx);
      const att = attributeIncome(shell, post, m.clicks, r);
      day.views += m.views; day.likes += m.likes; day.clicks += m.clicks; day.income += att.income;
      shell.followers += m.follows;
      const cs = shell.ctaStats[post.ctaStyle] = shell.ctaStats[post.ctaStyle] || { posts: 0, clicks: 0 };
      cs.posts += 1; cs.clicks += m.clicks;
      if (att.note) shell.memory.push(att.note + ` (${dayKey})`);
      if (m.viral) {
        events.push(`🔥 ${shell.name}: a ${platform} ${post.format} went viral — ${m.views.toLocaleString()} views, +${m.follows} followers.`);
        shell.memory.push(`Viral ${platform} ${post.format}: "${post.hook} ${post.topic}" — ${m.views.toLocaleString()} views.`);
      }
      shell.posts.push(post);
    }
    while (shell.posts.length > MAX_POSTS_ARCHIVE) shell.posts.shift();
    day.followers = shell.followers;
    shell.daily.push(day);
    if (shell.daily.length > 30) shell.daily.shift();
    shell.lastRunAt = now();

    /* Auto-Upload: queue today's best X post for real posting (X only —
       TikTok/IG/Shorts wait on future API integrations) */
    if (shell.autoUpload && queueAllowed) {
      const xPost = shell.posts.slice(-perDay).find(p => p.platform === "X");
      if (xPost) {
        const t = new Date(); t.setHours(t.getHours() + 1, 0, 0, 0);
        S().addQueueItem({
          cloneId: null,
          title: `🎭 ${shell.name} — daily drop`,
          text: (xPost.body.split("\n\n")[0] || xPost.body).slice(0, 270),
          dueAt: t.getTime()
        });
      }
    }
    return events;
  }

  function weeklyGrowthPct(shell) {
    if (shell.daily.length < 8) return null;
    const nowF = shell.followers;
    const weekAgo = shell.daily[shell.daily.length - 8].followers;
    if (!weekAgo) return null;
    return ((nowF - weekAgo) / weekAgo) * 100;
  }
  function dailyGrowthPct(shell) {
    if (shell.daily.length < 2) return 0;
    const prev = shell.daily[shell.daily.length - 2].followers || 1;
    return ((shell.followers - prev) / prev) * 100;
  }

  /* Step 4: evolve on engagement */
  function evolve(shell) {
    const events = [];
    const growth = weeklyGrowthPct(shell);
    if (growth == null) return events;

    /* resolve a running persona test */
    if (shell.personaTest && now() >= shell.personaTest.until) {
      const t = shell.personaTest;
      if (growth > (t.baseline == null ? 0 : t.baseline) + 1) {
        events.push(`🎭 ${shell.name}: persona test won — adopting ${shell.persona} permanently (${growth.toFixed(1)}%/wk vs ${t.baseline == null ? "?" : t.baseline.toFixed(1)}%).`);
        shell.memory.push(`Persona test adopted: ${shell.persona}.`);
      } else {
        shell.persona = t.prevPersona;
        events.push(`🎭 ${shell.name}: persona test failed — reverting to ${t.prevPersona}.`);
        shell.memory.push(`Persona test reverted to ${t.prevPersona}.`);
      }
      shell.personaTest = null;
      shell.lastEvolveAt = now();
      return events;
    }
    if (shell.personaTest) return events; /* test still running */

    if (now() - shell.lastEvolveAt < 7 * DAY) return events;
    shell.lastEvolveAt = now();

    if (growth > 10) {
      if (shell.postsPerDay < 5) {
        shell.postsPerDay += 1;
        events.push(`📈 ${shell.name} growing ${growth.toFixed(1)}%/week — scaling to ${shell.postsPerDay} posts/day.`);
        shell.memory.push(`Growth ${growth.toFixed(1)}%/wk → volume scaled to ${shell.postsPerDay}/day.`);
      }
    } else if (growth < 2) {
      const options = Object.keys(PERSONAS).filter(p => p !== shell.persona);
      const r = E().rng(E().hashStr(shell.id + ":swap:" + now()));
      const tryP = pick(r, options);
      shell.personaTest = { tryPersona: tryP, prevPersona: shell.persona, until: now() + 7 * DAY, baseline: growth };
      shell.persona = tryP;
      events.push(`⚠ ${shell.name} stagnant (${growth.toFixed(1)}%/wk) — auto-swapping persona to ${tryP} for a 7-day test.`);
      shell.memory.push(`Stagnation detected → 7-day persona test: ${tryP}.`);
    }
    return events;
  }

  /* Catch up all shells to the current sim day. */
  function process() {
    const st = S().state;
    const events = [];
    for (const shell of st.shells) {
      const start = shell.lastRunAt == null ? now() : shell.lastRunAt + DAY;
      let dayCount = shell.lastRunAt == null ? 1 : Math.floor((now() - shell.lastRunAt) / DAY);
      dayCount = Math.min(dayCount, 10); /* cap catch-up */
      let queued = false;
      for (let i = 0; i < dayCount; i++) {
        const dayKey = E().dateKey(new Date(start + i * DAY));
        const evs = runDay(shell, dayKey, shell.daily.length, !queued);
        if (shell.autoUpload) queued = true;
        events.push(...evs);
      }
      if (dayCount > 0) events.push(...evolve(shell));
    }
    if (st.shells.length) S().save();
    return events;
  }

