  function cloneShell(id) {
    const st = S().state;
    const src = st.shells.find(s => s.id === id);
    if (!src) return null;
    const base = src.name.replace(/\s+(II|III|IV|V|VI|VII|VIII|IX|X)$/i, "");
    const gen = (src.generation || 1) + 1;
    const roman = ["", "", "II", "III", "IV", "V", "VI", "VII", "VIII", "IX", "X"][Math.min(gen, 10)] || gen;
    const copy = createShell({
      name: `${base} ${roman}`,
      platforms: src.platforms, niche: src.niche, persona: src.persona,
      offerSource: src.offerSource, offerTargetProductId: src.offerTargetProductId,
      leadGenCloneId: src.leadGenCloneId, referenceContent: src.referenceContent,
      postsPerDay: src.postsPerDay, autoUpload: false,
      quality: Math.min(1.4, src.quality * 1.05),
      generation: gen, parentId: src.id
    });
    const best = bestHooks(src, 3);
    best.forEach(p => copy.memory.push(`Winning flow inherited: "${p.hook} ${p.topic}" (${p.metrics.views.toLocaleString()} views).`));
    S().logMemory("shell", `🎭 Shell "${src.name}" cloned → "${copy.name}" with its winning flows.`);
    S().save();
    return copy;
  }

  function crossPollinate(fromId, toId) {
    const st = S().state;
    const from = st.shells.find(s => s.id === fromId), to = st.shells.find(s => s.id === toId);
    if (!from || !to || from === to) return false;
    const bestStyle = Object.entries(from.ctaStats).sort((a, b) => b[1].clicks - a[1].clicks)[0];
    const hooks = bestHooks(from, 2);
    to.memory.push(`Cross-pollinated from ${from.name}: CTA style "${bestStyle ? bestStyle[0] : "generic"}"${hooks.length ? ` + hooks: ${hooks.map(h => `"${h.hook}"`).join(", ")}` : ""}.`);
    to.quality = Math.min(1.4, to.quality + 0.06);
    S().logMemory("shell", `🎭 CTA style copied from ${from.name} → ${to.name}.`);
    S().save();
    return true;
  }

  function bestHooks(shell, n) {
    return shell.posts.filter(p => p.metrics).sort((a, b) => b.metrics.views - a.metrics.views).slice(0, n || 5);
  }

  function stats() {
    const st = S().state;
    const followers = st.shells.reduce((a, s) => a + s.followers, 0);
    const income = st.shells.reduce((a, s) => a + s.daily.reduce((x, d) => x + d.income, 0), 0);
    const posts = st.shells.reduce((a, s) => a + s.daily.reduce((x, d) => x + 0, 0) + s.posts.length, 0);
    const emails = st.shells.reduce((a, s) => a + (s.emailList || 0), 0);
    return { shells: st.shells.length, followers, income, emails };
  }

  /* aggregate follower history for the weekly growth chart */
  function followerSeries() {
    const st = S().state;
    const labels = [], values = [];
    for (let i = 6; i >= 0; i--) {
      const key = E().dateKey(new Date(now() - i * DAY));
      let sum = 0;
      st.shells.forEach(s => {
        const rec = s.daily.filter(d => d.day <= key).slice(-1)[0];
        sum += rec ? rec.followers : 0;
      });
      labels.push("D-" + i);
      values.push(sum);
    }
    return { labels, values };
  }

